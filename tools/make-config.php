<?php
// CLI: generates google-ads-mcp-php-data/config.php from a dev env file (KEY=value lines, same keys as the old Node config.env).
// The env file path comes from GADS_CONFIG_ENV, default tools/dev-config.env (git-ignored; may be a symlink to your secrets store).
// Optional ADMIN_EMAIL in that file; otherwise leave it empty and use the setup wizard.
// Usage: php tools/make-config.php [public_base_url]   (defaults to the dev URL). Overwrites an existing config.php but keeps secret_key.
// Dev: auto_execute is always false. Configure production by hand based on config.example.php.
declare(strict_types=1);
if (PHP_SAPI !== 'cli') {
    http_response_code(404); exit;
} // CLI-only script, never over the web

$dataDir = dirname(__DIR__) . '/google-ads-mcp-php-data';
$baseUrl = rtrim($argv[1] ?? 'http://localhost/google-ads-php', '/');

$envFile = getenv('GADS_CONFIG_ENV') ?: __DIR__ . '/dev-config.env';
if (!is_file($envFile)) {
    fwrite(STDERR, "Missing env file: $envFile (set GADS_CONFIG_ENV or create tools/dev-config.env)\n");
    exit(1);
}
$env = parseEnv((string) file_get_contents($envFile));
$adminMail = $env['ADMIN_EMAIL'] ?? '';

$existing = is_file("$dataDir/config.php") ? (array) require "$dataDir/config.php" : [];
$list = fn(string $k): array => array_values(array_filter(array_map('trim', explode(',', $env[$k] ?? ''))));

$config = [
    'admin_email' => $adminMail,
    'public_base_url' => $baseUrl,
    'secret_key' => $existing['secret_key'] ?? base64_encode(random_bytes(32)),
    'debug' => true,
    'events_retention_days' => (int) ($env['EVENTS_RETENTION_DAYS'] ?? 14),
    'plan_ttl_hours' => (int) ($env['PLAN_TTL_HOURS'] ?? 24),
    'google_client_id' => $env['GOOGLE_CLIENT_ID'] ?? '',
    'google_client_secret' => $env['GOOGLE_CLIENT_SECRET'] ?? '',
    'allowed_email' => $env['ALLOWED_EMAIL'] ?? '',
    'app_clients' => $list('APP_CLIENTS') ?: ['claude-ai'],
    'ads_customer_id' => $env['ADS_CUSTOMER_ID'] ?? '',
    'ads_api_version' => $env['ADS_API_VERSION'] ?? 'v26',
    'ads_developer_token' => '',
    'ads_login_customer_id' => '',
    'max_daily_budget_pln' => (float) ($env['MAX_DAILY_BUDGET_PLN'] ?? 30),
    'auto_execute' => false, // DEV: never true
    'allow_preview_only' => ($env['ALLOW_PREVIEW_ONLY'] ?? 'false') === 'true',
    'account_time_zone' => $env['ACCOUNT_TIME_ZONE'] ?? 'Europe/Warsaw',
    'ga4_property_id' => $env['GA4_PROPERTY_ID'] ?? '',
    'allowed_url_hosts' => $list('ALLOWED_URL_HOSTS'),
    'landing_path_prefix' => $env['LANDING_PATH_PREFIX'] ?? '/lp2/',
    'lp2_forbidden_phrases' => $list('LP2_FORBIDDEN_PHRASES'),
    'lp2_thankyou_path' => $env['LP2_THANKYOU_PATH'] ?? '',
    'upload_password' => $env['UPLOAD_PASSWORD'] ?? '',
    'youtube_api_key' => $env['YOUTUBE_API_KEY'] ?? '',
    'lp2_admin_api_url' => $env['LP2_ADMIN_API_URL'] ?? '',
    'lp2_admin_api_token' => $env['LP2_ADMIN_API_TOKEN'] ?? '',
    'conversion_action_name' => $env['CONVERSION_ACTION_NAME'] ?? '',
    'conversion_action_id' => $env['CONVERSION_ACTION_ID'] ?? '',
    'conversion_tag_settings_url' => $env['CONVERSION_TAG_SETTINGS_URL'] ?? '',
    'default_geo_lat' => (float) ($env['DEFAULT_GEO_LAT'] ?? 52.2297),
    'default_geo_lng' => (float) ($env['DEFAULT_GEO_LNG'] ?? 21.0122),
    'default_geo_radius_km' => (int) ($env['DEFAULT_GEO_RADIUS_KM'] ?? 20),
    'default_geo_label' => $env['DEFAULT_GEO_LABEL'] ?? 'Warszawa',
];

if (!is_dir($dataDir)) {
    mkdir($dataDir, 0775, true);
}
file_put_contents("$dataDir/.htaccess", "Require all denied\n");
file_put_contents("$dataDir/config.php", "<?php\n// Generated by tools/make-config.php. Contains secrets — do not commit.\nreturn " . var_export($config, true) . ";\n");
chmod("$dataDir/config.php", 0660);
echo "Zapisano $dataDir/config.php (public_base_url=$baseUrl, auto_execute=false)\n";

/** KEY=VALUE with quotes; comments after #. */
function parseEnv(string $text): array
{
    $out = [];
    // The /u flag is required: without it \R matches byte 0x85 (the second byte of Polish "ą") and cuts UTF-8 values.
    foreach (preg_split('/\R/u', $text) as $line) {
        if (!preg_match('/^\s*([A-Z0-9_]+)=(.*)$/', $line, $m)) {
            continue;
        }
        $v = trim($m[2]);
        $out[$m[1]] = preg_match('/^(["\'])(.*)\1$/', $v, $q) ? $q[2] : $v;
    }
    return $out;
}
